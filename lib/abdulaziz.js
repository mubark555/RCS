// الأقسام اللي يقدر المستخدم يشوفها، بترتيب القائمة الجانبية
export function visibleGuides(can) {
  return SECTIONS.filter((s) => GUIDES[s.key] && can(s.key)).map((s) => ({ ...s, ...GUIDES[s.key] }));
}

// شرح القسم الحالي حسب المسار
export function guideForPath(path, can) {
  const key = sectionOfPath(path);
  if (!key || !GUIDES[key] || !can(key)) return null;
  const s = SECTIONS.find((x) => x.key === key);
  return { ...s, ...GUIDES[key] };
}
